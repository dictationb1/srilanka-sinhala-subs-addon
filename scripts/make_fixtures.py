# A couple of English lines used by the "credit" edge of the file.
CREDITS = ["Subtitles by Synthetic Team", "www.synthetic-subtitles.example"]


def _tc(ms: int) -> str:
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def build_srt(lines: list[str], start_ms: int = 1000, step_ms: int = 2500) -> str:
    out = []
    for i, line in enumerate(lines):
        s = start_ms + i * step_ms
        out.append(f"{i + 1}\n{_tc(s)} --> {_tc(s + step_ms - 400)}\n{line}\n")
    return "\n".join(out)


def _zipinfo(name: str, utf8: bool = True) -> zipfile.ZipInfo:
    info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = (0o644 & 0xFFFF) << 16
    return info


def write_zip(path: pathlib.Path, entries: list[tuple[str, bytes]]) -> None:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in entries:
            z.writestr(_zipinfo(name), data)
    path.write_bytes(buf.getvalue())


