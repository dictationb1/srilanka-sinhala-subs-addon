def _nested_zip() -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("Synthetic Movie (2008) - Piratelk.com/", "")
        z.writestr("Synthetic Movie (2008) - Piratelk.com/PirateLk.txt", "ad")
        z.writestr("Synthetic Movie (2008) - Piratelk.com/Synthetic Movie (2008) 480p BRRip x264 AAC-SYNTH.srt",
                   "1\n00:00:01,000 --> 00:00:02,000\nආයුබෝවන්\n")
        z.writestr("__MACOSX/junk/._nested.srt", "junk")
        z.writestr("../evil.srt", "evil")
    return buf.getvalue()


# ---------------------------------------------------------------- bug 1

def test_bug1_nested_zip_any_depth():
    b, ext = st.extract_archive(_nested_zip())
    assert ext == "srt"
    assert "ආයුබෝවන්" in st.decode(b)

    rb, rext = st.extract_archive(NESTED_ZIP.read_bytes())
    assert rext == "srt"
    assert st.parse(st.decode(rb)), "nested fixture produced no cues"

    zb, zext = st.extract_archive(FLAT_ZIP.read_bytes())
    assert zext == "srt"
    assert len(st.parse(st.decode(zb))) >= 12


