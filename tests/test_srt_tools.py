def test_bug4_batch_translate_validation():
    calls = []

    def bad(texts, ctx):        # wrong count once, then correct
        calls.append(1)
        if len(calls) == 1:
            return texts[:-1]
        return [f"si:{t}" for t in texts]

    cues = st.parse("\n\n".join(f"{i+1}\n00:00:0{i},100 --> 00:00:0{i},900\nLine {i} here." for i in range(6)))
    out = st.translate_cues(cues, bad, {"title": "Test"})
    assert len(out) == 6 and all(c["text"].startswith("si:") for c in out)
    assert all(c["start"] == o["start"] and c["end"] == o["end"] for c, o in zip(out, cues))


def test_bug4_translator_gives_up_gracefully():
    cues = st.parse("1\n00:00:01,000 --> 00:00:02,000\nKeep me\n")
    out = st.translate_cues(cues, lambda texts, ctx: [], {"title": "T"})
    assert out[0]["text"] == "Keep me", "a failing batch keeps the source line"


