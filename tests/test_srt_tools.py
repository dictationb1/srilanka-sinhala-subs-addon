def test_bug3_token_match_lowercase_and_group():
    assert st.token_match("INCEPTION.1080P.BluRay.X264-NTb", "inception.1080p.bluray.x264-ntb") > 0.9
    assert st.token_match("Movie.2026.1080p.WEBRip.x264-FLUX", "movie.2026.1080p.webrip.x264-avc") > 0.5
    assert st.token_match("A.2020.1080p.x264-YTS", "A.2020.1080p.x264-YTS") > 0.9
    assert st.token_match("", "whatever") == 0.0
    hi = st.token_match("The Dark Knight 2008 480p", "The Dark Knight 2008 480p")
    lo = st.token_match("The Dark Knight 2007 480p", "The Dark Knight 2008 480p")
    assert hi > lo


