def test_bug2_watermark_edges_only():
    cues = st.parse(
        "1\n00:00:01,000 --> 00:00:02,000\nCredit card\n\n"
        "2\n00:00:03,000 --> 00:00:04,000\nSome normal dialogue here.\n\n"
        "3\n00:00:05,000 --> 00:00:06,000\nwww.zoom.lk sync by Kasun\n\n"
        "4\n00:00:07,000 --> 00:00:08,000\nMiddle of movie line.\n"
    )
    kept = st.strip_watermarks(cues)
    assert any(c["text"] == "Credit card" for c in kept), "real dialogue must survive"
    assert not any("zoom.lk" in c["text"] for c in kept)
    assert st.is_watermark("Credits by John", 0, 10) is True
    assert st.is_watermark("Subtitles by John", 0, 10) is True
    assert st.is_watermark("I need the credit card.", 5, 10) is False


