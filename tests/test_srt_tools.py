def test_preindex_sigv4_and_key_contract():
    payload = b"1\n00:00:01,000 --> 00:00:02,000\nTest\n"
    url, headers = preindex.sign_v4(
        "https://example.r2.cloudflarestorage.com", "auto", "AKIDEXAMPLE", "SECRET",
        "subs-bucket", "preindex:https://zoom.lk/sub-download/1", payload,
        datetime(2026, 1, 1, tzinfo=timezone.utc),
    )
    assert re_fullmatch_hex(headers["Authorization"].rsplit("Signature=", 1)[-1])
    import urllib.parse
    decoded = urllib.parse.unquote(urllib.parse.urlparse(url).path)
    assert decoded == "/subs-bucket/preindex:https://zoom.lk/sub-download/1"
    assert headers["x-amz-date"] == "20260101T000000Z"
    # the Worker reads this exact literal key (src/cache.ts:preindexGet)
    assert preindex.r2_key("https://zoom.lk/sub-download/23752") == "preindex:https://zoom.lk/sub-download/23752"


def re_fullmatch_hex(sig: str) -> bool:
    return len(sig) == 64 and all(c in "0123456789abcdef" for c in sig)


