def test_bug5_timestamp_repair():
    cues = [
        {"start": 2000, "end": 1000, "text": "reversed"},
        {"start": 3000, "end": 3100, "text": "too short"},
        {"start": 3300, "end": 9000, "text": "small overlap"},
        {"start": 15000, "end": 16000, "text": "clean"},
        {"start": "junk", "end": 5, "text": "garbage"},
    ]
    fixed = st.repair_cues(cues)
    assert len(fixed) == 4
    assert fixed[0]["end"] - fixed[0]["start"] == 500
    assert fixed[1]["end"] - fixed[1]["start"] >= 500
    assert fixed[2]["start"] >= fixed[1]["end"]
    assert fixed[3]["start"] == 15000
    assert all(c["end"] > c["start"] for c in fixed)


