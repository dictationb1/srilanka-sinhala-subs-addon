def test_parse_emit_roundtrip():
    cues = st.parse("1\n00:00:01,000 --> 00:00:02,500\nHello\nworld\n\n2\n00:01:00,000 --> 00:01:02,000\nBye\n")
    assert len(cues) == 2 and cues[0]["text"] == "Hello\nworld"
    out = st.emit(cues)
    assert "00:00:01,000 --> 00:00:02,500" in out and "Bye" in out
    assert st.parse(out)[0]["start"] == 1000


